#!/usr/bin/env python3
"""
Independent replication of Rötteler & Beth (arXiv:quant-ph/9812070):
"Polynomial-Time Solution to the Hidden Subgroup Problem for a Class of
non-Abelian Groups"

Paper's group: W_n := Z_2^n wr Z_2 (wreath product), of order 2^(2n+1).
Elements: (x, y; a) with x, y in F_2^n, a in F_2.
Multiplication (paper eq., top of p.4):
    (g_1,...,g_n; tau) * (g'_1,...,g'_n; tau') = (g_{tau'(1)} g'_1, ..., g_{tau'(n)} g'_n; tau tau')
For A = Z_2^n and H = Z_2 = {0, t} with t swapping the two direct factors:
    (x, y; a) * (x', y'; a') = ( (x, y) if a'=0 else (y, x)  XOR (x', y'), a XOR a' )
which we implement as:
    if a' == 0: new = (x XOR x', y XOR y'; a XOR a')
    else:       new = (y XOR x', x XOR y'; a XOR a')

Pairing mu (paper Def 4.3):
    mu((x,y;0),(x',y';0)) = sum x_i x'_i + sum y_i y'_i     mod 2
    mu((x,y;0),(x',y';1)) = mu((x,y;1),(x',y';0))
      = sum x_i y'_i + sum x'_i y_i                          mod 2
      [i.e. the a XOR a' = 1 case]
    mu((x,y;1),(x',y';1)) = sum x_i x'_i + sum y_i y'_i + 1  mod 2

Fourier transform DFT_{W_n} (paper eq. between 6.1 and section 6):
    entry [g, h] = (-1)^mu(g,h) / sqrt(|W_n|)

We simulate the quantum algorithm classically on the 2^(2n+1)-dim group
algebra using numpy. Reproduces Algorithm 7.1.

Success criterion: for a hidden subgroup U of small order (2 or 4), recover
U with probability > 0.9 using O(n) measurements followed by the paper's
classical postprocessing.

Free-endpoint / real-simulation replication, no fabrication.
"""

import json
import os
import random
import sys
