def main():
    results = {
        "paper": "Bravyi, Browne, Calpin, Campbell, Gosset, Howard. "
                 "Simulation of quantum circuits by low-rank stabilizer "
                 "decompositions. Quantum 3, 181 (2019). arXiv:1808.00128",
        "scope": "small-t exact verification; numpy-only statevectors",
        "wall_clock_seconds": None,
    }
    t0 = time.time()

    # (a) Gottesman-Knill demo
    gk = []
    for n in (2, 3, 4):
        gk.append(gottesman_knill_demo(n=n, depth=40, seed=11))
    results["gottesman_knill_demo"] = gk

    # Flush
    with open(RESULTS_PATH, "w") as f:
        json.dump(results, f, indent=2, default=str)

    # (b)+(c) Stabilizer rank of |T>^t
    # Closed-form chi(|T>) = 2 check
    t1 = t_decomp_t1()
    results["chi_t1_closed_form"] = t1
    with open(RESULTS_PATH, "w") as f:
        json.dump(results, f, indent=2, default=str)

    # Build stabilizer-state lists for n=1,2,3
    print("Building 1-qubit stabilizer states...", flush=True)
    stab1 = all_nq_stabilizer_states(1)
    print(f"  |S_1| = {len(stab1)}", flush=True)

    print("Building 2-qubit stabilizer states...", flush=True)
    stab2 = all_nq_stabilizer_states(2)
    print(f"  |S_2| = {len(stab2)} (true value = 60)", flush=True)

    print("Building 3-qubit stabilizer states...", flush=True)
    stab3 = all_nq_stabilizer_states(3)
    print(f"  |S_3| = {len(stab3)} (true value = 1080)", flush=True)

    results["stabilizer_state_counts"] = {
        "n1_found": len(stab1), "n1_known": 6,
        "n2_found": len(stab2), "n2_known": 60,
        "n3_found": len(stab3), "n3_known": 1080,
    }
    with open(RESULTS_PATH, "w") as f:
        json.dump(results, f, indent=2, default=str)

    # Decompose |T>^1, |T>^2, |T>^3
    chi_results = []

    print("Searching chi(|T>^1)...", flush=True)
    r = t_decomp_general(1, stab1, max_rank=2)
    r["paper_chi"] = 2
    chi_results.append(r)

    print("Searching chi(|T>^2)...", flush=True)
    r = t_decomp_general(2, stab2, max_rank=4)
    r["paper_chi"] = 2  # known small-t exact value
    chi_results.append(r)

    print("Searching chi(|T>^3) with extended pool...", flush=True)
    # Two-pass: first try rank 2 or 3 with a large pool (C(1080,3)=210M is too
    # many; cap at 200K combos via islice in find_stab_decomposition). Then
    # fall back to rank 4 with normal pool as upper bound.
    r = t_decomp_general(3, stab3, max_rank=3, pool_override=1080)
    if r["chi_found"] is None:
        # Fall back: allow rank up to 4 (still useful upper bound)
        r2 = t_decomp_general(3, stab3, max_rank=4)
        r2["note"] = ("Greedy overlap-heuristic search up to rank 3 with "
                       "pool=1080 capped at 200000 combinations did NOT find "
                       "a chi=3 decomposition; reporting upper bound from "
                       "smaller pool fallback.")
        r = r2
    # Paper reports chi(|T>^3) <= 3 (and known exact = 3 by Bravyi-Gosset)
    r["paper_chi"] = 3
    chi_results.append(r)

    results["chi_results"] = chi_results
    with open(RESULTS_PATH, "w") as f:
        json.dump(results, f, indent=2, default=str)

    # (d) Output probability estimate via decomposition
    print("Estimating output probability via stabilizer decomposition...", flush=True)
    v, gates = small_clifford_t_circuit(n=3, seed=7)
    results["circuit"] = {"n_qubits": 3, "gates": [list(g) for g in gates]}
    # Pick highest-probability outcome
    probs = np.abs(v) ** 2
    out = int(np.argmax(probs))
    prob_est = estimate_prob_via_decomposition(3, 3, stab3, None, gates, out)
    results["probability_estimate"] = prob_est

    # Also a fixed bitstring
    out2 = 0
    prob_est2 = estimate_prob_via_decomposition(3, 3, stab3, None, gates, out2)
    results["probability_estimate_b0"] = prob_est2

    results["wall_clock_seconds"] = round(time.time() - t0, 2)
    with open(RESULTS_PATH, "w") as f:
        json.dump(results, f, indent=2, default=str)
    print("Done. Wrote", RESULTS_PATH)


if __name__ == "__main__":
    main()
