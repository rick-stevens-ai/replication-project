def random_subgroup(n, target_order, rng, elts, max_tries=200):
    """Sample a random subgroup of W_n with given order by picking random
    generators until closure hits the target."""
    identity = (tuple([0] * n), tuple([0] * n), 0)
    for _ in range(max_tries):
        num_gens = 1 if target_order == 2 else 2
        gens = []
        for _ in range(num_gens):
            g = identity
            while g == identity:
                g = elts[rng.randrange(len(elts))]
            gens.append(g)
        U = subgroup_closure(gens, n)
        if len(U) == target_order:
            return gens, U
    return None, None


def main():
    n = 2
    rng = random.Random(2026 - 7 - 5)
    print(f"[setup] n={n}, |W_n| = 2^{2*n+1} = {2**(2*n+1)}", flush=True)

    t0 = time.time()
    F, elts = build_dft(n)
    N = len(elts)
    print(f"[setup] built DFT of shape {F.shape} in {time.time()-t0:.2f}s", flush=True)

    # Sanity: DFT is orthogonal
    err_orth = np.max(np.abs(F @ F.T - np.eye(N)))
    print(f"[sanity] max|F F^T - I| = {err_orth:.2e}", flush=True)
    assert err_orth < 1e-10, "DFT not orthogonal!"

    # Sanity: closure of a random element
    identity = (tuple([0] * n), tuple([0] * n), 0)
    for _ in range(5):
        g = elts[rng.randrange(N)]
        while g == identity:
            g = elts[rng.randrange(N)]
        H = subgroup_closure([g], n)
        assert identity in H
        assert all(inverse(h) in H for h in H), f"closure not closed under inv: {H}"
    print("[sanity] closure under inverse OK", flush=True)

    # Run 3 random trials with |H|=2 and 3 more with |H|=4 for good measure.
    num_samples = 4 * n * 4  # paper: expected 4n reps; use 4x for margin
    print(f"[run] using {num_samples} samples per trial (paper: expected 4n = {4*n})", flush=True)

    results = []
    for target_order in [2, 4]:
        for trial in range(3):
            gens, U_true = random_subgroup(n, target_order, rng, elts)
            if U_true is None:
                print(f"[trial {trial} order {target_order}] could not sample subgroup, skipping")
                continue
            # 10 independent runs, count successes
            successes = 0
            n_reps = 10
            for rep in range(n_reps):
                U_rec = run_algorithm(gens, n, F, elts, num_samples, rng)
                if U_rec == U_true:
                    successes += 1
            p = successes / n_reps
            gens_str = [{"x": list(g[0]), "y": list(g[1]), "a": g[2]} for g in gens]
            print(f"[trial {trial} |U|={target_order}] gens={gens} p_success = {successes}/{n_reps} = {p:.2f}", flush=True)
            results.append({
                "trial": trial,
                "target_order": target_order,
                "gens": gens_str,
                "true_U_size": len(U_true),
                "n_reps": n_reps,
                "successes": successes,
                "prob_success": p,
                "num_samples": num_samples,
            })

    all_ok = all(r["prob_success"] > 0.9 for r in results if r["target_order"] == 2)
    verdict_note = "REPLICATED" if all_ok else "PARTIAL"
    out = {
        "paper": "arXiv:quant-ph/9812070 (Rötteler & Beth 1998)",
        "n": n,
        "group_order": N,
        "dft_orthogonality_err": float(err_orth),
        "trials": results,
        "success_criterion": "success prob > 0.9 for all |H|=2 trials",
        "verdict_note": verdict_note,
        "num_queries_per_run": num_samples,
        "poly_log_G": 4 * n,
    }
    outpath = os.path.join(os.path.dirname(__file__), "results.json")
    with open(outpath, "w") as fh:
        json.dump(out, fh, indent=2)
    print(f"[done] wrote {outpath}", flush=True)
    print(f"[VERDICT] {verdict_note}", flush=True)


if __name__ == "__main__":
    main()
